import { act, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { expect, it, vi } from 'vitest';
import { fresh, medicine } from '../support/fixtures';
import { renderApp } from '../support/render';

it('adds only after review, navigates to details and archives/restores a medicine', async () => {
  const store = fresh();
  const user = userEvent.setup();
  renderApp(store);
  expect(screen.getByText(/No medicines scheduled today/)).toBeInTheDocument();
  await user.click(screen.getByRole('link', { name: 'Add medicine' }));
  await user.click(screen.getByRole('button', { name: 'Review medicine' }));
  expect(screen.getByLabelText('Medicine name')).toHaveFocus();
  await user.type(screen.getByLabelText('Medicine name'), 'Sample medicine');
  await user.type(screen.getByLabelText('Strength / dosage'), '5 mg');
  await user.clear(screen.getByLabelText(/Daily times/));
  await user.type(screen.getByLabelText(/Daily times/), '25:00');
  await user.clear(screen.getByLabelText('Supply in doses'));
  await user.type(screen.getByLabelText('Supply in doses'), '-1');
  await user.click(screen.getByRole('button', { name: 'Review medicine' }));
  expect(screen.getByText('Use times such as 08:00, 18:00')).toBeInTheDocument();
  expect(screen.getByText('Enter a whole number, zero or more')).toBeInTheDocument();
  expect(screen.getByLabelText(/Daily times/)).toHaveAttribute('aria-invalid', 'true');
  await user.clear(screen.getByLabelText(/Daily times/));
  await user.type(screen.getByLabelText(/Daily times/), '18:00, 08:00, 08:00');
  await user.clear(screen.getByLabelText('Supply in doses'));
  await user.type(screen.getByLabelText('Supply in doses'), '8');
  await user.click(screen.getByRole('button', { name: 'Review medicine' }));
  expect(screen.getByText('Enter each daily time only once')).toBeInTheDocument();
  expect(screen.getByLabelText(/Daily times/)).toHaveFocus();
  expect(store.active).toEqual([]);
  await user.clear(screen.getByLabelText(/Daily times/));
  await user.type(screen.getByLabelText(/Daily times/), '18:00, 08:00');
  await user.click(screen.getByRole('button', { name: 'Review medicine' }));
  expect(screen.getByRole('heading', { name: 'Review medicine', level: 1 })).toHaveFocus();
  expect(store.active).toEqual([]);
  await user.click(screen.getByRole('link', { name: 'Edit details' }));
  expect(screen.getByLabelText(/Daily times/)).toHaveValue('08:00, 18:00');
  await user.type(screen.getByLabelText('Instructions (optional)'), 'Sample instructions');
  await user.click(screen.getByRole('button', { name: 'Review medicine' }));
  await user.click(screen.getByRole('button', { name: 'Save medicine' }));
  expect(screen.getByRole('heading', { name: 'Medicine details', level: 1 })).toHaveFocus();
  expect(store.active).toHaveLength(1);
  await user.click(screen.getByRole('link', { name: 'Edit medicine' }));
  await user.clear(screen.getByLabelText('Strength / dosage'));
  await user.type(screen.getByLabelText('Strength / dosage'), '10 mg');
  await user.click(screen.getByRole('button', { name: 'Review medicine' }));
  await user.click(screen.getByRole('button', { name: 'Save medicine' }));
  expect(store.active[0]).toMatchObject({ strength: '10 mg', times: ['08:00', '18:00'] });
  await user.click(screen.getByRole('button', { name: 'Archive medicine' }));
  expect(store.active).toEqual([]);
  await user.click(screen.getByRole('button', { name: 'Restore medicine' }));
  expect(store.active).toHaveLength(1);
  await user.click(screen.getByRole('link', { name: 'Medicines', exact: true }));
  expect(screen.getByText('Low supply · Check your refill')).toBeInTheDocument();
});

it('records doses, preserves Undo after five minutes, and corrects history', async () => {
  const store = fresh();
  store.put(medicine);
  const user = userEvent.setup();
  renderApp(store);
  await user.click(screen.getByRole('link', { name: 'Open Sample medicine dose at 08:00' }));
  await user.click(screen.getByRole('button', { name: 'Mark Taken' }));
  expect(screen.getByText('Status: Taken')).toBeInTheDocument();
  vi.useFakeTimers();
  act(() => vi.advanceTimersByTime(300000));
  vi.useRealTimers();
  await user.click(screen.getByRole('button', { name: 'Undo last change' }));
  expect(screen.getByText('Status: Due')).toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: 'Skip dose' }));
  await user.click(screen.getByRole('link', { name: 'History', exact: true }));
  await user.click(screen.getByRole('button', { name: 'Taken', exact: true }));
  expect(store.status(store.doseKey(medicine, '08:00'))).toBe('Taken');
  await user.click(screen.getByRole('button', { name: 'Due', exact: true }));
  expect(screen.getByText('No doses recorded yet.')).toBeInTheDocument();
  expect(store.state.doses).toEqual({});
});

it('saves symptoms and filters summaries by the selected date range', async () => {
  const store = fresh();
  store.put(medicine);
  store.record(store.doseKey(medicine, '08:00'), 'Taken');
  store.record('2026-09-20|1|08:00', 'Skipped');
  const user = userEvent.setup();
  renderApp(store, '/settings');
  await user.click(screen.getByRole('link', { name: 'Symptoms', exact: true }));
  await user.click(screen.getByRole('button', { name: 'Save symptom' }));
  expect(screen.getByLabelText('Symptom', { exact: true })).toHaveFocus();
  expect(screen.getByText('Enter a symptom')).toBeInTheDocument();
  await user.type(screen.getByLabelText('Symptom', { exact: true }), ' Headache ');
  await user.type(screen.getByLabelText('Notes (optional)'), ' After lunch ');
  await user.selectOptions(screen.getByLabelText('Severity'), 'Moderate');
  await user.click(screen.getByRole('button', { name: 'Save symptom' }));
  expect(screen.getByRole('status')).toHaveTextContent('Symptom saved on this device.');
  expect(store.state.symptoms[0]).toMatchObject({ name: 'Headache', severity: 'Moderate', notes: 'After lunch' });
  expect(screen.getByLabelText('Symptom', { exact: true })).toHaveValue('');
  await user.click(screen.getByRole('link', { name: '← Back' }));
  await user.click(screen.getByRole('link', { name: 'Appointment summary' }));
  expect(screen.getByText('1 taken of 1 recorded doses')).toBeInTheDocument();
  await user.selectOptions(screen.getByLabelText('Date range'), '30');
  expect(screen.getByText('1 taken of 2 recorded doses')).toBeInTheDocument();
  expect(screen.getByText(/Headache · Moderate/)).toBeInTheDocument();
});

